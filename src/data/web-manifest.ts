import { SITE, defaultDescription } from './site';
import { getTool } from './tools';

/**
 * Android long-press shortcuts (TWA brief step 1): at most 4. Names come from tools.ts, never hardcoded here.
 * twa/twa-manifest.json copies these; tests/unit/manifest.test.ts keeps the two in step.
 */
export const SHORTCUT_SLUGS = ['id-photo', 'pdf-merge', 'hwp-to-pdf', 'photo-compress'] as const;

export const SHORTCUT_ICON = { src: '/brand/icon-192.png', sizes: '192x192', type: 'image/png' } as const;

/** Launcher labels are cut at about 10–12 characters; a tool name longer than SHORT_LABEL_MAX gets a short label here. */
export const SHORT_LABEL_MAX = 12;
export const SHORTCUT_SHORT_NAMES: Partial<Record<(typeof SHORTCUT_SLUGS)[number], string>> = { 'id-photo': '증명사진 규격' };

/** Web app manifest (brief Polish P.10; TWA step 1). The icons are generated by scripts/gen-brand.mjs. */
export function webManifest() {
  return {
    id: '/',
    name: SITE.defaultTitle,
    short_name: SITE.name,
    description: defaultDescription(),
    start_url: '/',
    scope: '/',
    display: 'standalone',
    background_color: '#ffffff',
    theme_color: SITE.themeColor,
    lang: 'ko',
    categories: ['productivity', 'utilities'],
    icons: [
      { src: '/brand/icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: '/brand/icon-512.png', sizes: '512x512', type: 'image/png' },
      { src: '/brand/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
    shortcuts: SHORTCUT_SLUGS.map((slug) => {
      const name = getTool(slug).name;
      return { name, short_name: SHORTCUT_SHORT_NAMES[slug] ?? name, url: `/${slug}/`, icons: [SHORTCUT_ICON] };
    }),
  };
}
