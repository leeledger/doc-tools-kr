// F1 probe c (Bob, 2026-10-20): table in a middle paragraph (paragraph count), spacingBefore unit, cell height.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../../node_modules/@rhwp/core/', import.meta.url);
const mod = await import(new URL('rhwp.js', root).href);
globalThis.measureTextWidth = (font, text) => { const px = Number(/(\d+(?:\.\d+)?)px/.exec(font)?.[1] ?? 16); let w = 0; for (const ch of text) { const cp = ch.codePointAt(0); w += cp >= 0xac00 && cp <= 0xd7af ? px : px * 0.55; } return w; };
await mod.default({ module_or_path: readFileSync(new URL('rhwp_bg.wasm', root)) });
const D = mod.HwpDocument;
const out = [];
const log = (k, v) => { const s = `${k} ${typeof v === 'string' ? v.slice(0, 300) : JSON.stringify(v)}`; out.push(s); console.log(s); };
const tryc = (k, f) => { try { log(k, f()); } catch (e) { log(k + ' THROW', String(e)); } };
const doc = D.createEmpty(); doc.createBlankDocument();
doc.insertText(0, 0, 0, 'A');
doc.splitParagraph(0, 0, 1);
doc.splitParagraph(0, 1, 0);
doc.insertText(0, 2, 0, 'C');
log('paras before', doc.getParagraphCount(0));
let t; tryc('table at para 1', () => (t = doc.createTableEx(JSON.stringify({ sectionIdx: 0, paraIdx: 1, charOffset: 0, rowCount: 2, colCount: 2, treatAsChar: true, colWidths: [10000, 31952] }))));
const p = JSON.parse(t);
log('paras after', doc.getParagraphCount(0));
for (let i = 0; i < doc.getParagraphCount(0); i++) tryc('para len ' + i, () => doc.getParagraphLength(0, i));
tryc('bbox y before spacing', () => JSON.parse(doc.getTableCellBboxes(0, p.paraIdx, p.controlIdx))[0].y);
tryc('spacingBefore 1000', () => doc.applyParaFormat(0, p.paraIdx, JSON.stringify({ spacingBefore: 1000 })));
tryc('para props', () => JSON.parse(doc.getParaPropertiesAt(0, p.paraIdx)).spacingBefore);
tryc('bbox y after spacing', () => JSON.parse(doc.getTableCellBboxes(0, p.paraIdx, p.controlIdx))[0].y);
tryc('cell height set', () => doc.setCellProperties(0, p.paraIdx, p.controlIdx, 0, JSON.stringify({ height: 2835 })));
tryc('bbox h', () => JSON.parse(doc.getTableCellBboxes(0, p.paraIdx, p.controlIdx)).map((b) => [b.cellIdx, b.h, b.w]));
tryc('cell va', () => doc.setCellProperties(0, p.paraIdx, p.controlIdx, 1, JSON.stringify({ verticalAlign: 1 })));
const e = doc.exportHwpWithReport(); log('loss', e.contentLoss()); const b = e.takeBytes(); e.free();
const r = new D(b); log('reload pages', r.pageCount()); log('reload paras', r.getParagraphCount(0));
tryc('reload bbox', () => JSON.parse(r.getTableCellBboxes(0, p.paraIdx, p.controlIdx)).map((x) => [x.cellIdx, x.h, x.w, x.y]));
writeFileSync(new URL('probe-f1c.out.txt', import.meta.url), out.join('\n') + '\n');
