// F1 probes (Bob, 2026-10-20): formatting call keys, table colWidths, multiline in cells, merge cell order, determinism.
// node handoff/sources/form1020/probe-f1.mjs   (writes nothing to the repo except probe-f1.out.txt next to it)
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../../node_modules/@rhwp/core/', import.meta.url);
const mod = await import(new URL('rhwp.js', root).href);
globalThis.measureTextWidth = (font, text) => { const px = Number(/(\d+(?:\.\d+)?)px/.exec(font)?.[1] ?? 16); let w = 0; for (const ch of text) { const cp = ch.codePointAt(0); w += cp >= 0xac00 && cp <= 0xd7af ? px : px * 0.55; } return w; };
await mod.default({ module_or_path: readFileSync(new URL('rhwp_bg.wasm', root)) });
const D = mod.HwpDocument;
const out = [];
const log = (k, v) => { const s = `${k} ${typeof v === 'string' ? v.slice(0, 600) : JSON.stringify(v)}`; out.push(s); console.log(s); };
const tryc = (k, f) => { try { log(k, f()); } catch (e) { log(k + ' THROW', String(e)); } };
const doc = D.createEmpty();
doc.createBlankDocument();
tryc('charProps0', () => doc.getCharPropertiesAt(0, 0, 0));
tryc('paraProps0', () => doc.getParaPropertiesAt(0, 0));
tryc('insert title', () => doc.insertText(0, 0, 0, '위 임 장'));
tryc('applyChar bold size', () => doc.applyCharFormat(0, 0, 0, 5, JSON.stringify({ bold: true, fontSize: 2000 })));
tryc('charProps after', () => doc.getCharPropertiesAt(0, 0, 1));
tryc('applyPara center', () => doc.applyParaFormat(0, 0, JSON.stringify({ alignment: 'center' })));
tryc('paraProps after', () => doc.getParaPropertiesAt(0, 0));
tryc('split', () => doc.splitParagraph(0, 0, 5));
tryc('paraProps p1 (inherits?)', () => doc.getParaPropertiesAt(0, 1));
tryc('charProps p1', () => doc.getCharPropertiesAt(0, 1, 0));
tryc('pagedef', () => doc.getPageDef ? doc.getPageDef(0) : 'n/a');
tryc('pageInfo', () => doc.getPageInfo(0));
let t;
tryc('tableEx', () => (t = doc.createTableEx(JSON.stringify({ sectionIdx: 0, paraIdx: 1, charOffset: 0, rowCount: 3, colCount: 3, treatAsChar: false, colWidths: [6000, 9000, 27000] }))));
const p = JSON.parse(t || '{}');
tryc('dims', () => doc.getTableDimensions(0, p.paraIdx, p.controlIdx));
for (let c = 0; c < 9; c++) tryc('cellProps ' + c, () => doc.getCellProperties(0, p.paraIdx, p.controlIdx, c));
tryc('merge col0 rows0-2', () => doc.mergeTableCells(0, p.paraIdx, p.controlIdx, 0, 0, 2, 0));
tryc('dims after merge', () => doc.getTableDimensions(0, p.paraIdx, p.controlIdx));
for (let c = 0; c < 9; c++) tryc('cellProps after ' + c, () => doc.getCellProperties(0, p.paraIdx, p.controlIdx, c));
tryc('cell newline insert', () => doc.insertTextInCell(0, p.paraIdx, p.controlIdx, 2, 0, 0, '첫줄\n둘째줄'));
tryc('cell paras after newline', () => doc.getCellParagraphCount(0, p.paraIdx, p.controlIdx, 2));
tryc('cell 4 insert', () => doc.insertTextInCell(0, p.paraIdx, p.controlIdx, 4, 0, 0, '가나다라'));
tryc('cell split', () => doc.splitParagraphInCell(0, p.paraIdx, p.controlIdx, 4, 0, 2));
tryc('cell 4 paras', () => doc.getCellParagraphCount(0, p.paraIdx, p.controlIdx, 4));
tryc('cell para fmt', () => doc.applyParaFormatInCell(0, p.paraIdx, p.controlIdx, 0, 0, JSON.stringify({ alignment: 'center' })));
tryc('cell char fmt', () => doc.applyCharFormatInCell(0, p.paraIdx, p.controlIdx, 4, 0, 0, 2, JSON.stringify({ bold: true })));
tryc('bad para', () => doc.applyParaFormat(0, 99, '{}'));
tryc('paras', () => doc.getParagraphCount(0));
const exp = (d) => { const e = d.exportHwpWithReport(); const loss = e.contentLoss(); const b = e.takeBytes(); e.free(); return [loss, b]; };
const [loss, b1] = exp(doc);
log('loss', loss);
const [, b2] = exp(doc);
log('bytes', [b1.length, b2.length, Buffer.compare(Buffer.from(b1), Buffer.from(b2)) === 0 ? 'same-run identical' : 'same-run differ']);
const r = new D(b1);
log('reload pages', r.pageCount());
const svg = r.renderPageSvg(0);
log('svg has 둘째줄', ['둘', '째', '줄'].every((c) => svg.includes(c)));
writeFileSync(new URL('probe-f1.out.txt', import.meta.url), out.join('\n') + '\n');
