const isStr = (x) => typeof x === 'string';
const VALUE_CHECKS = {
  e: (x) => EVENTS.includes(x),
  t: (x) => TOOLS.includes(x) || LAND_PAGES.includes(x), // a LAND_PAGES value only on land (checked below)
  c: (x) => CODE_RE.test(x),
  p: (x) => PHASES.includes(x),
  o: (x) => Object.hasOwn(SETTINGS, x) || x === NEXT_KEY || x === OUT_KEY,
  v: () => true, // checked against o below
  g: (x) => GUIDE_RE.test(x),
  dl: (x) => x === '0' || x === '1',
  via: (x) => VIAS.includes(x),
  d: (x) => DEVICES.includes(x),
  br: (x) => BROWSER_RE.test(x),
  b: (x) => BUILD_RE.test(x),
  us: (x) => UTM_SOURCES.includes(x) || x === 'other',
  uc: (x) => CAMPAIGN_RE.test(x),
};
const REQUIRED = ['e', 't', 'via', 'd', 'b', 'w'];

/**
 * The event in `text` (the request body), or null when it is not exactly a whitelisted event: over 512 bytes, not a
 * JSON object, an unknown key, a value outside its list, a key on the wrong event type, or a required key missing.
 * The result holds every blob key ('' when absent) and w.
 */
export function validate(text) {
  if (!isStr(text) || new TextEncoder().encode(text).length > MAX_BODY) return null;
  let o;
  try {
    o = JSON.parse(text);
  } catch {
    return null;
  }
  if (!o || typeof o !== 'object' || Array.isArray(o)) return null;
  for (const k of Object.keys(o)) if (!KEYS.has(k)) return null;
  for (const k of REQUIRED) if (!Object.hasOwn(o, k)) return null;
  if (!Number.isInteger(o.w) || o.w < 1 || o.w > 100) return null;
  for (const k of BLOB_KEYS) {
    if (!Object.hasOwn(o, k)) continue;
    if (!isStr(o[k]) || !VALUE_CHECKS[k](o[k])) return null;
    if (ONLY[k] && !ONLY[k].includes(o.e)) return null;
  }
  if (o.e === 'fail' && !(Object.hasOwn(o, 'c') && Object.hasOwn(o, 'p'))) return null;
  if (o.e === 'arrive' && !(Object.hasOwn(o, 'g') && Object.hasOwn(o, 'dl'))) return null;
  if (Object.hasOwn(o, 'o') !== Object.hasOwn(o, 'v')) return null;
  if (Object.hasOwn(o, 'us') !== Object.hasOwn(o, 'uc')) return null;
  if (LAND_PAGES.includes(o.t) && o.e !== 'land') return null;
  if (o.e === 'land' && (!Object.hasOwn(o, 'us') || o.via !== 'direct' || (Object.hasOwn(o, 'g') && o.t !== 'guide'))) return null;
  if (o.e === 'next') {
    if (o.o !== NEXT_KEY || !TOOLS.includes(o.v)) return null;
  } else if (o.e === 'out') {
    if (o.o !== OUT_KEY || !outDests(Object.hasOwn(o, 'g') ? GUIDE_OUT : TOOL_OUT, o.t).includes(o.v)) return null;
  } else if (Object.hasOwn(o, 'o') && (o.o === NEXT_KEY || o.o === OUT_KEY || !SETTINGS[o.o].includes(o.v))) return null;
  // A download names a setting only where DOWNLOAD_SETTING allows it (ROMANIZE1016 D6: 영문 이름 변환기 복사, o = form),
  // and a download-only setting rides on nothing else (Richard R0-R3 should-fix 1: no form on a start of any tool).
  if (o.e !== 'download' && Object.hasOwn(o, 'o') && Object.values(DOWNLOAD_SETTING).includes(o.o)) return null;
  if (o.e === 'download' && Object.hasOwn(o, 'o') && !(Object.hasOwn(DOWNLOAD_SETTING, o.t) && DOWNLOAD_SETTING[o.t] === o.o)) return null;
  const ev = { w: o.w };
  for (const k of BLOB_KEYS) ev[k] = Object.hasOwn(o, k) ? o[k] : '';
  return ev;
}

/** The Analytics Engine data point of a validated event (row schema at the top of this file). */
export function toDataPoint(ev) {
  return { indexes: [ev.t], blobs: BLOB_KEYS.map((k) => ev[k]), doubles: [ev.w] };
}

// ---------- reading back (SQL API) ----------

const N = 'SUM(_sample_interval * double1)';

/** The six queries of the admin page and the weekly report (chains: 이어서 하기, blob2 sender -> blob6 receiver; outs: 링크 누름, blob2 tool, blob7 guide ('' on a result screen), blob6 dest). Throws on a period or dataset outside the whitelist. */
export function usageSql(dataset, days) {
  if (!DATASET_RE.test(dataset ?? '')) throw new Error('usage: invalid dataset name');
  if (!PERIODS.includes(days)) throw new Error('usage: invalid period');
  const where = `timestamp > NOW() - INTERVAL '${days}' DAY`;
  return {
    events: `SELECT blob2 AS tool, blob1 AS event, blob9 AS via, ${N} AS n FROM ${dataset} WHERE ${where} GROUP BY blob2, blob1, blob9 FORMAT JSON`,
    fails: `SELECT blob2 AS tool, blob3 AS code, blob4 AS phase, ${N} AS n FROM ${dataset} WHERE ${where} AND blob1 = 'fail' GROUP BY blob2, blob3, blob4 ORDER BY n DESC LIMIT 20 FORMAT JSON`,
    settings: `SELECT blob2 AS tool, blob5 AS setting, blob6 AS value, ${N} AS n FROM ${dataset} WHERE ${where} AND (blob1 = 'start' OR blob1 = 'download') AND blob5 != '' GROUP BY blob2, blob5, blob6 ORDER BY n DESC LIMIT 500 FORMAT JSON`,
    guides: `SELECT blob7 AS guide, blob2 AS tool, blob8 AS dl, ${N} AS n FROM ${dataset} WHERE ${where} AND blob1 = 'arrive' GROUP BY blob7, blob2, blob8 ORDER BY n DESC LIMIT 500 FORMAT JSON`,
    chains: `SELECT blob2 AS tool, blob6 AS dest, ${N} AS n FROM ${dataset} WHERE ${where} AND blob1 = 'next' GROUP BY blob2, blob6 ORDER BY n DESC LIMIT 500 FORMAT JSON`,
    outs: `SELECT blob2 AS tool, blob7 AS guide, blob6 AS dest, ${N} AS n FROM ${dataset} WHERE ${where} AND blob1 = 'out' GROUP BY blob2, blob7, blob6 ORDER BY n DESC LIMIT 500 FORMAT JSON`,
  };
}

/**
 * The admin page's comparison query: event totals of the period before the current one (days 2N..N ago). Alias "kind",
 * not "event", so the two are told apart. Throws on a period outside COMPARE_PERIODS or a bad dataset name.
 */
export function usagePrevSql(dataset, days) {
  if (!DATASET_RE.test(dataset ?? '')) throw new Error('usage: invalid dataset name');
  if (!COMPARE_PERIODS.includes(days)) throw new Error('usage: invalid comparison period');
  return `SELECT blob1 AS kind, ${N} AS n FROM ${dataset} WHERE timestamp > NOW() - INTERVAL '${2 * days}' DAY AND timestamp <= NOW() - INTERVAL '${days}' DAY GROUP BY blob1 FORMAT JSON`;
}

