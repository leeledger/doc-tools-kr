/**
 * Query rows -> display tables (strings only, not yet escaped) for the weekly report (markdown), the totals for its
 * summary, and raw numbers for the admin page (scripts/lib/admin-view.mjs): kpi (rate in percent, null without
 * attempts), tools (TOOLS order), failRows (codeLabel null for a code outside FAIL_LABELS) and chains (이어서 하기:
 * total, pairs sender -> receiver, perTool sent/received; rows with a tool outside TOOLS are dropped) and outs (링크 누름:
 * total, rows per result screen and dest with the share of that tool's successes, then one row per dest for all guides
 * summed (share '-'); a pair outside TOOL_OUT / GUIDE_OUT is dropped).
 * @param {{ events?: Array<Record<string, any>>, fails?: Array<Record<string, any>>, settings?: Array<Record<string, any>>, guides?: Array<Record<string, any>>, chains?: Array<Record<string, any>>, outs?: Array<Record<string, any>> }} rows
 */
export function shapeUsage({ events = [], fails = [], settings = [], guides = [], chains = [], outs = [] }) {
  const per = new Map();
  const cell = (tool) => {
    if (!per.has(tool)) per.set(tool, { pick: 0, start: 0, success: 0, fail: 0, download: 0, guide: { success: 0, fail: 0 }, direct: { success: 0, fail: 0 }, embed: { success: 0, fail: 0 } });
    return per.get(tool);
  };
  let arrive = 0;
  for (const r of events) {
    if (TOOLS.includes(r.tool) && r.event === 'arrive') arrive += num(r.n);
    // next is counted from the chains query and out from the outs query: neither is a step of the tool's own funnel.
    // land (a marked-link landing, REQ1014-A D4) is read by the campaign table only.
    if (!TOOLS.includes(r.tool) || !EVENTS.includes(r.event) || r.event === 'arrive' || r.event === 'next' || r.event === 'out' || r.event === 'land') continue;
    const c = cell(r.tool);
    const n = num(r.n);
    c[r.event] += n;
    if ((r.event === 'success' || r.event === 'fail') && VIAS.includes(r.via)) c[r.via][r.event] += n;
  }
  const tools = TOOLS.filter((t) => per.has(t));
  let success = 0;
  let fail = 0;
  let start = 0;
  for (const t of tools) {
    success += per.get(t).success;
    fail += per.get(t).fail;
    start += per.get(t).start;
  }

  const bySetting = new Map();
  for (const r of settings) {
    const list = bySetting.get(r.tool) ?? [];
    list.push(r);
    bySetting.set(r.tool, list);
  }
  const settingRows = [];
  for (const t of [...TOOLS, ...[...bySetting.keys()].filter((k) => !TOOLS.includes(k))]) {
    const list = (bySetting.get(t) ?? []).sort((a, b) => num(b.n) - num(a.n)).slice(0, 5);
    for (const r of list) settingRows.push([label(TOOL_LABELS, t), label(SETTING_LABELS, r.setting), label(Object.hasOwn(SETTING_VALUE_LABELS, r.setting) ? SETTING_VALUE_LABELS[r.setting] : VALUE_LABELS, r.value), count(num(r.n))]);
  }

  const arrivals = new Map();
  for (const r of guides) {
    const key = `${r.guide}\u0000${r.tool}`;
    const a = arrivals.get(key) ?? { guide: r.guide, tool: r.tool, n: 0, dl: 0 };
    a.n += num(r.n);
    if (r.dl === '1') a.dl += num(r.n);
    arrivals.set(key, a);
  }

  const pairMap = new Map();
  for (const r of chains) {
    if (!TOOLS.includes(r.tool) || !TOOLS.includes(r.dest)) continue;
    const key = `${r.tool}\u0000${r.dest}`;
    const p = pairMap.get(key) ?? { from: r.tool, fromLabel: TOOL_LABELS[r.tool], to: r.dest, toLabel: TOOL_LABELS[r.dest], n: 0 };
    p.n += num(r.n);
    pairMap.set(key, p);
  }
  const pairs = [...pairMap.values()].sort((a, b) => b.n - a.n || TOOLS.indexOf(a.from) - TOOLS.indexOf(b.from) || TOOLS.indexOf(a.to) - TOOLS.indexOf(b.to));
  const perChain = new Map(TOOLS.map((t) => [t, { tool: t, label: TOOL_LABELS[t], sent: 0, received: 0 }]));
  let chainTotal = 0;
  for (const p of pairs) {
    chainTotal += p.n;
    perChain.get(p.from).sent += p.n;
    perChain.get(p.to).received += p.n;
  }
  // Array.prototype.sort is stable, so ties keep TOOLS order.
  const perTool = [...perChain.values()].filter((c) => c.sent > 0 || c.received > 0).sort((a, b) => b.sent + b.received - (a.sent + a.received));

  // Tool rows: one per (tool, dest), share = that tool's own successes in the period (the block shows only with a result).
  // Guide rows: one per dest, every guide summed, no share. Stable sorts: ties keep TOOLS, then OUT_DESTS order.
  const toolOut = new Map();
  const guideOut = new Map();
  for (const r of outs) {
    const fromGuide = typeof r.guide === 'string' && r.guide !== '';
    if (!outDests(fromGuide ? GUIDE_OUT : TOOL_OUT, r.tool).includes(r.dest)) continue;
    const map = fromGuide ? guideOut : toolOut;
    const key = fromGuide ? r.dest : `${r.tool}\u0000${r.dest}`;
    map.set(key, (map.get(key) ?? 0) + num(r.n));
  }
  const toolRows = TOOLS.flatMap((t) =>
    OUT_DESTS.filter((d) => toolOut.has(`${t}\u0000${d}`)).map((d) => {
      const n = toolOut.get(`${t}\u0000${d}`);
      return { tool: t, place: TOOL_LABELS[t], dest: d, label: OUT_LABELS[d], n, share: rate(n, per.get(t)?.success ?? 0) };
    }),
  );
  const guideRows = OUT_DESTS.filter((d) => guideOut.has(d)).map((d) => ({ tool: null, place: OUT_GUIDE_PLACE, dest: d, label: OUT_LABELS[d], n: guideOut.get(d), share: '-' }));
  const outRows = [...toolRows.sort((a, b) => b.n - a.n), ...guideRows.sort((a, b) => b.n - a.n)];
  const outTotal = outRows.reduce((sum, r) => sum + r.n, 0);

  return {
    totals: { success, fail, rate: rate(success, success + fail) },
    kpi: { start, success, fail, rate: success + fail > 0 ? (success / (success + fail)) * 100 : null, arrive },
    tools: tools.map((t) => {
      const c = per.get(t);
      return { tool: t, label: TOOL_LABELS[t], pick: c.pick, start: c.start, success: c.success, fail: c.fail, download: c.download, guide: { ...c.guide }, direct: { ...c.direct }, embed: { ...c.embed } };
    }),
    failRows: fails.slice(0, 20).map((r) => {
      const code = String(r.code ?? '');
      return { tool: String(r.tool ?? ''), toolLabel: label(TOOL_LABELS, r.tool), code, codeLabel: Object.hasOwn(FAIL_LABELS, code) ? FAIL_LABELS[code] : null, phaseLabel: label(PHASE_LABELS, r.phase), n: num(r.n) };
    }),
    chains: { total: chainTotal, pairs, perTool },
    outs: { total: outTotal, rows: outRows },
    tables: [
      {
        title: '도구별',
        head: ['도구', '파일 고름', '처리 시작', '성공', '실패', '성공률', '내려받음'],
        rows: tools.map((t) => {
          const c = per.get(t);
          return [label(TOOL_LABELS, t), count(c.pick), count(c.start), count(c.success), count(c.fail), rate(c.success, c.success + c.fail), count(c.download)];
        }),
      },
      {
        title: '실패 이유',
        head: ['도구', '오류 코드', '단계', '횟수'],
        rows: fails.slice(0, 20).map((r) => [label(TOOL_LABELS, r.tool), String(r.code ?? ''), label(PHASE_LABELS, r.phase), count(num(r.n))]),
      },
      { title: '많이 쓴 설정', head: ['도구', '설정', '값', '횟수'], rows: settingRows },
      {
        title: '안내 글에서 도구로',
        head: ['안내 글', '도구', '넘어옴', '딥링크 비율'],
        rows: [...arrivals.values()].sort((a, b) => b.n - a.n).map((a) => [label(GUIDE_TITLES, a.guide), label(TOOL_LABELS, a.tool), count(a.n), DEEP_LINK_TOOLS.includes(a.tool) ? rate(a.dl, a.n) : NO_DEEP_LINK]),
      },
      {
        title: '도구별 성공률 (안내에서 온 경우, 바로 온 경우, 다른 누리집에 넣은 도구)',
        head: ['도구', '안내에서 옴', '바로 옴', '다른 누리집'],
        rows: tools.map((t) => {
          const c = per.get(t);
          return [label(TOOL_LABELS, t), rate(c.guide.success, c.guide.success + c.guide.fail), rate(c.direct.success, c.direct.success + c.direct.fail), rate(c.embed.success, c.embed.success + c.embed.fail)];
        }),
      },
      { title: '이어서 하기 (보낸 도구 → 받은 도구)', head: ['보낸 도구', '받은 도구', '횟수'], rows: pairs.map((p) => [p.fromLabel, p.toLabel, count(p.n)]) },
      { title: '이어서 하기 도구별 합계', head: ['도구', '보냄', '받음'], rows: perTool.map((c) => [c.label, count(c.sent), count(c.received)]) },
      { title: '상품·사진관 링크', head: ['자리', '링크', '누른 횟수', '저장 성공 대비(%)'], rows: outRows.map((r) => [r.place, r.label, count(r.n), r.share]) },
    ],
  };
}

export const EMPTY_TABLE = '기록이 아직 없어요.';

export function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[ch]);
}

const mdCell = (s) => String(s).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');

/**
 * The shaped tables as markdown (`level`: heading level of each title) or as HTML (`format` "html", every value
 * escaped). Both read the same shaped rows.
 */
export function renderTables(shaped, format = 'md', level = 3) {
  if (format === 'html') {
    return shaped.tables
      .map((t) => {
        const title = `<h2>${escapeHtml(t.title)}</h2>`;
        if (!t.rows.length) return `${title}\n<p>${EMPTY_TABLE}</p>`;
        const head = `<tr>${t.head.map((h) => `<th scope="col">${escapeHtml(h)}</th>`).join('')}</tr>`;
        const body = t.rows.map((r) => `<tr>${r.map((c) => `<td>${escapeHtml(c)}</td>`).join('')}</tr>`).join('\n');
        return `${title}\n<table>\n<thead>${head}</thead>\n<tbody>\n${body}\n</tbody>\n</table>`;
      })
      .join('\n');
  }
  const h = '#'.repeat(level);
  return shaped.tables
    .map((t) => {
      if (!t.rows.length) return `${h} ${t.title}\n\n${EMPTY_TABLE}`;
      const lines = [`| ${t.head.map(mdCell).join(' | ')} |`, `| ${t.head.map(() => '---').join(' | ')} |`, ...t.rows.map((r) => `| ${r.map(mdCell).join(' | ')} |`)];
      return `${h} ${t.title}\n\n${lines.join('\n')}`;
    })
    .join('\n\n');
}
