// Writes scripts/lib/guide-titles.mjs ({ slug: title } of published guides and hubs) for the /admin/ tables and the
// weekly report, which run without the content collection (Pages Function, ops script). Run after adding or
// renaming a guide: `node scripts/gen-guide-titles.mjs`. tests/unit/visits.test.ts fails when it is stale.
// A JS module, not JSON: the Pages build's bundler rejects JSON import attributes (`with { type: 'json' }`), and Node
// needs them for a plain .json import (production build failure, 2026-10-08).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, isMain } from './ops/lib/common.mjs';
import { guideTitles } from './ops/lib/guides.mjs';

export const serialize = (titles) => `// Generated by scripts/gen-guide-titles.mjs. Do not edit.\nexport default ${JSON.stringify(titles, null, 2)};\n`;

if (isMain(import.meta)) {
  const titles = guideTitles();
  writeFileSync(join(ROOT, 'scripts', 'lib', 'guide-titles.mjs'), serialize(titles));
  console.log(`gen-guide-titles: wrote ${Object.keys(titles).length} titles to scripts/lib/guide-titles.mjs`);
}
